/** "[S1] Title, publisher year — locator. url (passage …, library …)"; older saved citations have no passage ID. */
function sourceLine(src, lang = 'en') {
  const t = T[lang] || T.en;
  return `[${src.id}] ${src.title}${src.cite ? `, ${SN.date(src.cite, lang).text}` : ''}${src.heading ? ` — ${headingOf(src, lang)}` : ''}${src.url ? `. ${src.url}` : ''}` +
    (src.passage_id ? ` (${t.passage} ${src.passage_id}${src.library_build ? `, ${t.library} ${src.library_build}` : ''})` : '') +
    sourceNotes(src, lang);
}
// locator part of the saved heading ("p. 12 — Section") in the document language; section names stay as written
const headingOf = (src, lang) => (src.locator && src.locatorLabel && String(src.heading).startsWith(src.locatorLabel)
  ? SN.locator(src.locator, lang) + src.heading.slice(src.locatorLabel.length) : src.heading);
/** Review status and every warning that came with the source, in the document language where a translation exists. */
function sourceNotes(src, lang) {
  const t = T[lang] || T.en;
  const one = text => { const r = SN.localize(text, lang); return r.original ? `${r.text} [${t.original_en}]` : r.text; };
  const notes = [...(src.review_status ? [`${t.review}: ${one(src.review_status)}`] : []), ...[...new Set([...(src.warnings || []), ...(src.caveats || [])])].map(one),
    ...(src.qualification_details || []).map(q => one(`${q.id}: ${q.title}: ${q.text}`))];
  return notes.length ? `. ${t.source_notes}: ${notes.join(' · ')}` : '';
}
// Source titles stay as published (not translated and not reformatted).
function sourceList(sources, lang) {
  const t = T[lang] || T.en;
  return [new Paragraph({ style: 'SourcesHeading', keepNext: true, children: [new TextRun(t.sources)] }),
    ...sources.map((src, i) => new Paragraph({ spacing: { after: 40, line: 250 }, keepNext: i < sources.length - 1, indent: { left: 284, hanging: 284 },
      children: [new TextRun({ size: MD.SIZE.tableNote, color: MD.COLORS.muted, text: sourceLine(src, lang) })] }))];
}

/** How a section was produced, for its label and the overall status. */
function sectionState(s, proposal) {
  const failed = (proposal.ai_failed || []).some(x => x.key === s.key);
  const ai = s.ai === true || (s.ai === undefined && proposal.ai === true);
  const quotesAi = !ai && s.quotes_plan_summary === 'ai';
  // older proposals did not record the quote; a failed summary then used the saved plan summary
  const quotes = quotesAi || (!ai && s.key === 'summary' && failed && s.quotes_plan_summary === undefined);
  return { ai, failed, quotesAi, incomplete: ai ? CW.mayBeIncomplete(s.text) : quotes && CW.mayBeIncomplete(s.text, { anyParagraph: true }) };
}

/** Title for old proposals saved without a utility name ("GCF pathway — "): fall back to the assessment name. */
function documentTitle(proposal, name) {
  const title = String(proposal.title || 'Proposal');
  const base = title.replace(/\s*—\s*$/, '');
  return /—\s*$/.test(title) && name ? `${base} — ${name}` : base;
}

async function buildProposalDocx({ lang = 'en', proposal, results, actions, plan, profile, meta }) {
  const t = T[lang] || T.en;
  const names = stageNameMap(lang);
  const L = o => (o && typeof o === 'object') ? (o[lang] || o.en) : (o || '');
  const f = (n, d) => fmt(n, d, lang);
  const name = profile?.name || results?.name || '';
  const sections = proposal.sections || [];
  const states = sections.map(s => sectionState(s, proposal));

  const children = [
    new Paragraph({ heading: HeadingLevel.TITLE, children: [new TextRun(documentTitle(proposal, name))] }),
    new Paragraph({ spacing: { after: 120 }, children: [new TextRun({ text: [profile?.name || results?.name, profile?.location].filter(Boolean).join(' · '), color: MD.COLORS.muted })] }),
    new Paragraph({ spacing: { after: 200 }, children: [new TextRun({ text: `${t.prepared}: ${CW.formatDate(new Date().toISOString().slice(0, 10), lang)}`, size: MD.SIZE.note, color: MD.COLORS.muted })] }),
  ];
  // concise overall status: how the draft was produced, what failed and what may be incomplete
  const aiCount = states.filter(x => x.ai).length;
  const failed = proposal.ai_failed || [];
  const lines = failed.length
    ? [t.status_failed(failed.map(x => x.title).join('; ')), ...(aiCount ? [t.status_mixed(aiCount, sections.length - aiCount)] : [])]
    : [aiCount === sections.length && sections.length ? t.status_ai(sections.length) : aiCount === 0 ? t.status_template : t.status_mixed(aiCount, sections.length - aiCount)];
  const incomplete = sections.filter((s, i) => states[i].incomplete).map(s => s.title);
  if (incomplete.length) lines.push(t.status_incomplete(incomplete.join('; ')));
  lines.push(t.note);
  if (t.original_language) lines.push(t.original_language);
  children.push(new Paragraph({ style: 'StatusBox', keepNext: true, children: [new TextRun({ text: t.status_head, bold: true })] }),
    ...lines.map((l, i) => new Paragraph({ style: 'StatusBox', keepLines: true, ...(i === lines.length - 1 ? { spacing: { after: 280 } } : {}), children: [new TextRun(MD.chem(l))] })));

  let lists = 0;
  sections.forEach((s, i) => {
    const st = states[i];
    children.push(new Paragraph({ heading: HeadingLevel.HEADING_1, keepNext: true, keepLines: true, children: [new TextRun(s.title)] }));
    const label = st.ai ? t.sec_ai : st.quotesAi ? t.sec_quotes_ai : st.failed ? t.sec_template_failed : t.sec_template;
    children.push(new Paragraph({ style: 'SectionStatus', keepNext: true, children: [new TextRun(label)] }));
    if (st.incomplete) children.push(new Paragraph({ style: 'SectionWarning', keepNext: true, children: [new TextRun(t.sec_incomplete)] }));
    const body = MD.toDocx(s.text, { title: s.title, stageNames: names, listBase: lists, contentWidth: CONTENT });
    lists += body.lists;
    children.push(...body.children);
    if (s.sources?.length) children.push(...sourceList(s.sources, lang));
    if (s.key === 'baseline' || s.key === 'rationale') children.push(...resultsBlock(s.title));
    if (s.key === 'actions' || s.key === 'impact') children.push(...actionsBlock(s.title));
    if (s.key === 'plan' || s.key === 'logframe') children.push(...planBlock(s.title));
  });
  function resultsBlock(title) {
    if (!results) return [];
    const rows = Object.entries(results.byStage).filter(([, v]) => v.count)
      .map(([k, v]) => [names[k] || k, v.total == null ? 'Unknown' : f(v.total / 1000, 1), f(v.energy_kwh)]);
    rows.push([`**${t.total}**`, `**${results.totals.total == null ? 'Unknown' : f(results.totals.total / 1000, 1)}**`, `**${f(results.energy_kwh)}**`]);
    return [
      ...(sameTitle(title, t.results) ? [] : [caption(t.results)]),
      MD.table([t.stage, t.ghg, t.energy], rows, [CONTENT - 2 * 2300, 2300, 2300]),
      ...(results.water_balance || []).map(w => note(`${w.name}: NRW ${w.nrw_pct.value == null ? 'Unknown' : f(w.nrw_pct.value,2)+'%'}; ${lang === 'id' ? 'kehilangan air' : 'water loss'} ${w.water_loss_pct.value == null ? 'Unknown' : f(w.water_loss_pct.value,2)+'%'}.`)),
      note(`${t.period}: ${CW.formatDate(results.period.start, lang)} – ${CW.formatDate(results.period.end, lang)} · ${t.gwp}: ${CW.gwpLabel(results.gwp.report, lang)} · ${t.grid}: ${f(results.factors.conv_kwh_co2, 3)} kgCO2/kWh`),
    ];
  }
  function actionsBlock(title) {
    const sel = (actions || []).filter(a => a.rule !== 'baseline');
    if (!sel.length) return [];
    const long = sel.length > LONG_TABLE / 3, dup = sameTitle(title, t.selected);
    return [
      ...(long || dup ? [] : [caption(t.selected)]),
      MD.table([t.option, t.expected, t.condition], sel.map(a => CA.isCustom(a)
        ? [[`**${a.id}** · ${a.title}`, ...customLines(a, lang, { results, meta })], expectedText(a, lang), '–']
        : [[`**${a.id}** · ${L(a.title)}`, addressesText(a, lang)].filter(Boolean), expectedText(a, lang), L(a.condition)]), [3700, 2700, CONTENT - 6400],
        { stageNames: names, ...(long && !dup ? { caption: t.selected } : {}) }),
      ...(sel.some(CA.isCustom) ? [note(uiText('ca_doc_note', lang), { spacing: { before: 80, after: 40 } })] : []),
      ...(sel.length > 1 ? [note(uiText('combined_not_assessed', lang))] : [note('', { spacing: { after: 120 } })]),
    ];
  }
  function planBlock(title) {
    if (!plan?.tasks?.length) return [];
    // long task lists can run over a page: the caption then goes inside the table (see MD.table)
    const long = plan.tasks.length > LONG_TABLE, dup = sameTitle(title, t.plan);
    return [
      ...(long || dup ? [] : [caption(t.plan)]),
      MD.table([t.task, t.owner, t.start, t.dur], plan.tasks.map(k => [[`**${k.id}** ${k.name}`, `${k.action}${k.action_origin === 'user' ? ` (${uiText('user_proposed', lang)})` : ''}`], k.owner || '–', String(k.start_week), String(k.weeks)]),
        [CONTENT - 2400 - 2 * 1150, 2400, 1150, 1150], { stageNames: names, ...(long && !dup ? { caption: t.plan } : {}) }),
      note('', { spacing: { after: 160 } }),
    ];
  }

  const footer = new Footer({ children: [new Paragraph({ alignment: AlignmentType.CENTER, children: [
    new TextRun({ size: MD.SIZE.tableNote, color: MD.COLORS.muted, children: [`${t.page} `, PageNumber.CURRENT, ` ${t.of} `, PageNumber.TOTAL_PAGES] })] })] });
  const doc = new Document({
    title: documentTitle(proposal, name), creator: 'ChatWater Resilience', description: t.note,
    numbering: { config: [{ reference: MD.NUMBERING.reference, levels: MD.NUMBERING.levels.map(l => ({ ...l, format: LevelFormat[{ decimal: 'DECIMAL', lowerLetter: 'LOWER_LETTER', lowerRoman: 'LOWER_ROMAN' }[l.format]] })) }] },
    styles: {
      default: {
        document: { run: { font: MD.FONT, size: MD.SIZE.body, language: { value: lang === 'id' ? 'id-ID' : 'en-GB' } }, paragraph: { spacing: { after: 120, line: 276 } } },
        title: { run: { font: MD.FONT, size: 44, bold: true, color: MD.COLORS.accent }, paragraph: { spacing: { after: 80 } } },
        heading1: { run: { font: MD.FONT, size: 30, bold: true, color: MD.COLORS.accent }, paragraph: { spacing: { before: 360, after: 80 }, keepNext: true, keepLines: true } },
        heading2: { run: { font: MD.FONT, size: 25, bold: true, color: MD.COLORS.accent }, paragraph: { spacing: { before: 240, after: 80 }, keepNext: true, keepLines: true } },
        heading3: { run: { font: MD.FONT, size: 23, bold: true }, paragraph: { spacing: { before: 200, after: 60 }, keepNext: true, keepLines: true } },
        heading4: { run: { font: MD.FONT, size: 22, bold: true, italics: true }, paragraph: { spacing: { before: 160, after: 60 }, keepNext: true, keepLines: true } },
      },
      paragraphStyles: [
        { id: 'Caption', name: 'Caption', basedOn: 'Normal', next: 'Normal', quickFormat: true,
          run: { size: 21, bold: true, color: MD.COLORS.accent }, paragraph: { spacing: { before: 240, after: 80 }, keepNext: true, keepLines: true } },
        { id: 'SectionStatus', name: 'Section status', basedOn: 'Normal', next: 'Normal',
          run: { size: MD.SIZE.note, italics: true, color: MD.COLORS.muted }, paragraph: { spacing: { before: 0, after: 140 }, keepNext: true } },
        { id: 'SectionWarning', name: 'Section warning', basedOn: 'Normal', next: 'Normal',
          run: { size: MD.SIZE.note, bold: true, color: '9A3412' }, paragraph: { spacing: { before: 0, after: 140 }, keepNext: true,
            border: { left: { style: BorderStyle.SINGLE, size: 18, color: 'C2410C', space: 6 } } } },
        { id: 'StatusBox', name: 'Draft status', basedOn: 'Normal', next: 'Normal',
          run: { size: 20, color: '333333' }, paragraph: { spacing: { before: 0, after: 60, line: 260 }, indent: { left: 120, right: 120 },
            shading: { type: ShadingType.CLEAR, color: 'auto', fill: 'EEF4F5' } } },
        { id: 'SourcesHeading', name: 'Sources heading', basedOn: 'Normal', next: 'Normal',
          run: { size: MD.SIZE.note, bold: true, color: MD.COLORS.muted }, paragraph: { spacing: { before: 160, after: 40 }, keepNext: true } },
      ],
    },
    sections: [{ properties: { page: { size: { width: PAGE.width, height: PAGE.height }, margin: { top: PAGE.margin, bottom: PAGE.margin, left: PAGE.margin, right: PAGE.margin, footer: 600 } } },
      footers: { default: footer }, children }],
  });
  return Packer.toBuffer(doc);
}

function expectedText(a, lang) {
  const L = o => (o && typeof o === 'object') ? (o[lang] || o.en) : (o || '');
  if (CA.isCustom(a)) return `${uiText('ghg_not_quantified', lang)} · ${uiText('energy_not_quantified', lang)}`;
  const parts = [];
  if (a.expected_kgco2 && AS.isQuantified(a, 'ghg')) parts.push(`${fmt(a.expected_kgco2 / 1000, 0, lang)} tCO2eq`);
  if (a.expected_kwh && AS.isQuantified(a, 'kwh')) parts.push(`${fmt(a.expected_kwh, 0, lang)} kWh`);
  if (!parts.length) return L(a.expected_text) || '–';
  return parts.join(' · ') + (a.scenario ? ` (${lang === 'id' ? 'skenario' : 'scenario'})` : '')
    + (a.rule !== 'baseline' && !AS.isQuantified(a, 'kwh') ? ` · ${uiText('energy_not_quantified', lang)}` : '');
}

const uiText = (k, lang) => (UI[lang] && UI[lang][k]) ?? UI.en[k] ?? k;
const benefitStatus = a => ({ kgco2: AS.benefitStatus(a, 'ghg'), kwh: AS.benefitStatus(a, 'kwh') });

/**
 * Where a user-proposed action applies, in the output language. The substage is found by its
 * ChatWater ID in the source assessment's metadata; its name comes from the recalculated results.
 */
function customLocationText(a, lang, { results, meta } = {}) {
  const stage = p => stageLabel(p, lang);
  if (!a.location || a.location.at !== 'substage') return uiText('loc_assessment', lang);
  if (!meta) return stage(a.location.prefix);
  const r = CA.resolveLocation(a, meta);
  if (r.at === 'missing') return `${stage(a.location.prefix)} (${uiText('ca_location_missing', lang)})`;
  const name = results ? ((results.substages || []).filter(s => s.prefix === r.prefix)[r.index] || {}).name : null;
  return `${stage(r.prefix)}${name ? ' › ' + name : ''}`;
}
/** Lines describing a user-proposed action: origin and review status first, then the user's own text unchanged. */
function customLines(a, lang, ctx) {
  const u = k => uiText(k, lang);
  return [
    `${u('user_proposed')} · ${u('not_reviewed')}`,
    `${u('ca_description')}: ${a.description}`,
    a.problem ? `${u('ca_problem')}: ${a.problem}` : null,
    `${u('ca_location')}: ${customLocationText(a, lang, ctx)}`,
  ].filter(Boolean);
}

/** "Addresses: problem — location. Source: classification" in the output language, from action-sources.js. */
function addressesText(a, lang) {
  const d = AS.describe(a);
  if (!d) return '';
  const u = k => uiText(k, lang);
  const stage = p => stageLabel(p, lang);
  const loc = l => !l ? '' : l.at === 'utility' ? u('loc_utility') : l.at === 'stages' ? l.stages.map(stage).join(', ') : stage(l.prefix);
  const sources = d.mapped
    ? d.sources.map(s => `${u('src_' + s.source)}${s.location.at !== 'substage' ? ` (${loc(s.location)})` : ''}: ${u('cls_' + (s.classification || 'pending'))}`)
    : [u('cls_pending')];
  const where = loc(d.location);
  return `${u('addresses')}: ${u(d.mapped ? 'pb_' + d.problem : 'pb_unmapped')}${where ? ` — ${where}` : ''}. ${sources.join('; ')}`;
}

function csv(rows) {
  return rows.map(r => r.map(v => {
    const s = String(v ?? '');
    return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
  }).join(',')).join('\n');
}

