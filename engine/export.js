const border = { style: BorderStyle.SINGLE, size: 4, color: 'BFC9CC' };
const borders = { top: border, bottom: border, left: border, right: border };
function table(headers, rows, widths) {
  const total = widths.reduce((a, b) => a + b, 0);
  const cell = (text, i, head) => new TableCell({
    borders, width: { size: widths[i], type: WidthType.DXA },
    shading: head ? { fill: '1F6F78', type: ShadingType.CLEAR, color: 'auto' } : undefined,
    margins: { top: 60, bottom: 60, left: 100, right: 100 },
    children: [new Paragraph({
      alignment: (!head && i > 0 && /^[\d,.–-]+$/.test(String(text))) ? AlignmentType.RIGHT : AlignmentType.LEFT,
      children: [new TextRun({ text: String(text ?? ''), bold: head, color: head ? 'FFFFFF' : undefined, size: 19 })],
    })],
  });
  return new Table({
    width: { size: total, type: WidthType.DXA }, columnWidths: widths,
    rows: [new TableRow({ tableHeader: true, children: headers.map((h, i) => cell(h, i, true)) }),
      ...rows.map(r => new TableRow({ children: r.map((c, i) => cell(c, i, false)) }))],
  });
}

function sourceList(sources) {
  return sources.map(src => new Paragraph({ spacing: { after: 40 }, children: [new TextRun({ size: 17, color: '555555',
    text: `[${src.id}] ${src.title}${src.cite ? `, ${src.cite}` : ''}${src.heading ? ` — ${src.heading}` : ''}${src.url ? `. ${src.url}` : ''}` })] }));
}

function textToParagraphs(text) {
  const out = [];
  for (const block of String(text || '').split(/\n\s*\n/)) {
    for (const line of block.split('\n')) {
      const l = line.trim();
      if (!l) continue;
      if (/^[-*•]\s+/.test(l)) out.push(new Paragraph({ bullet: { level: 0 }, children: [new TextRun(l.replace(/^[-*•]\s+/, ''))] }));
      else out.push(new Paragraph({ spacing: { after: 120 }, children: [new TextRun(l.replace(/\*\*/g, ''))] }));
    }
  }
  return out;
}

async function buildProposalDocx({ lang = 'en', proposal, results, actions, plan, profile }) {
  const t = T[lang] || T.en, S = STAGE_NAMES[lang] || STAGE_NAMES.en;
  const L = o => (o && typeof o === 'object') ? (o[lang] || o.en) : (o || '');
  const children = [
    new Paragraph({ heading: HeadingLevel.TITLE, children: [new TextRun(proposal.title || 'Proposal')] }),
    new Paragraph({ children: [new TextRun({ text: [profile?.name, profile?.location].filter(Boolean).join(' · '), color: '555555' })] }),
    new Paragraph({ spacing: { after: 240 }, children: [new TextRun({ text: t.note, italics: true, size: 18, color: '777777' })] }),
  ];
  for (const s of proposal.sections || []) {
    children.push(new Paragraph({ heading: HeadingLevel.HEADING_1, children: [new TextRun(s.title)] }));
    children.push(...textToParagraphs(s.text));
    if (s.sources?.length) children.push(...sourceList(s.sources));
    if (s.key === 'baseline' || s.key === 'rationale') children.push(...resultsBlock());
    if (s.key === 'actions' || s.key === 'impact') children.push(...actionsBlock());
    if (s.key === 'plan' || s.key === 'logframe') children.push(...planBlock());
  }
  function resultsBlock() {
    if (!results) return [];
    const rows = Object.entries(results.byStage).filter(([, v]) => v.count)
      .map(([k, v]) => [S[k], fmt(v.total / 1000, 1), fmt(v.energy_kwh)]);
    rows.push([t.total, fmt(results.totals.total / 1000, 1), fmt(results.energy_kwh)]);
    return [
      new Paragraph({ heading: HeadingLevel.HEADING_3, children: [new TextRun(t.results)] }),
      table([t.stage, t.ghg, t.energy], rows, [4200, 2400, 2400]),
      new Paragraph({ spacing: { before: 120, after: 200 }, children: [new TextRun({ size: 18, color: '555555',
        text: `${t.period}: ${results.period.start} – ${results.period.end} · ${t.gwp}: ${results.gwp.report} · ${t.grid}: ${results.factors.conv_kwh_co2} kgCO2/kWh` })] }),
    ];
  }
  function actionsBlock() {
    const sel = (actions || []).filter(a => a.rule !== 'baseline');
    if (!sel.length) return [];
    return [
      new Paragraph({ heading: HeadingLevel.HEADING_3, children: [new TextRun(t.selected)] }),
      table([t.option, t.expected, t.condition], sel.map(a => [
        `${a.id} · ${L(a.title)}`, expectedText(a, lang), L(a.condition)]), [3600, 2800, 2600]),
      new Paragraph({ text: '' }),
    ];
  }
  function planBlock() {
    if (!plan?.tasks?.length) return [];
    return [
      new Paragraph({ heading: HeadingLevel.HEADING_3, children: [new TextRun(t.plan)] }),
      table([t.task, t.owner, t.start, t.dur], plan.tasks.map(k => [`${k.id} ${k.action} — ${k.name}`, k.owner, k.start_week, k.weeks]), [4600, 2400, 1000, 1000]),
      new Paragraph({ text: '' }),
    ];
  }
  const doc = new Document({
    styles: {
      default: { document: { run: { font: 'Arial', size: 21 } } },
      paragraphStyles: [
        { id: 'Heading1', name: 'Heading 1', basedOn: 'Normal', next: 'Normal', quickFormat: true,
          run: { size: 28, bold: true, color: '1F6F78' }, paragraph: { spacing: { before: 280, after: 120 }, outlineLevel: 0 } },
        { id: 'Heading3', name: 'Heading 3', basedOn: 'Normal', next: 'Normal', quickFormat: true,
          run: { size: 22, bold: true }, paragraph: { spacing: { before: 160, after: 80 }, outlineLevel: 2 } },
      ],
    },
    sections: [{ properties: { page: { size: { width: 11906, height: 16838 }, margin: { top: 1300, bottom: 1300, left: 1300, right: 1300 } } }, children }],
  });
  return Packer.toBuffer(doc);
}

function expectedText(a, lang) {
  const L = o => (o && typeof o === 'object') ? (o[lang] || o.en) : (o || '');
  const parts = [];
  if (a.expected_kgco2) parts.push(`${fmt(a.expected_kgco2 / 1000, 0)} tCO2eq`);
  if (a.expected_kwh) parts.push(`${fmt(a.expected_kwh)} kWh`);
  if (!parts.length) return L(a.expected_text) || '–';
  return parts.join(' · ') + (a.scenario ? ` (${lang === 'id' ? 'skenario' : 'scenario'})` : '');
}

function csv(rows) {
  return rows.map(r => r.map(v => {
    const s = String(v ?? '');
    return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
  }).join(',')).join('\n');
}

async function buildZip(state, docxBuffer) {
  const zip = new JSZip();
  const lang = state.lang || 'en';
  if (docxBuffer) zip.file('proposal.docx', docxBuffer);
  zip.file('ecam/assessments-ecam-format.json', JSON.stringify(state.assessments || [], null, 2));
  zip.file('ecam/results.json', JSON.stringify(state.results || [], null, 2));
  if (state.results?.length) {
    const rows = [['assessment', 'stage', 'substage', 'total_kgCO2eq', 'co2', 'ch4_as_co2eq', 'n2o_as_co2eq', 'energy_kWh']];
    for (const r of state.results) for (const s of r.substages)
      rows.push([r.name, `${s.level}/${s.sublevel}`, s.name, s.ghg?.total, s.ghg?.co2, s.ghg?.ch4, s.ghg?.n2o, s.energy_kwh]);
    zip.file('ecam/results-by-substage.csv', csv(rows));
  }
  zip.file('actions/selected-actions.json', JSON.stringify(state.selectedActions || [], null, 2));
  if (state.plan?.tasks) {
    zip.file('plan/project-plan.csv', csv([['id', 'action', 'task', 'owner', 'start_week', 'weeks', 'depends_on'],
      ...state.plan.tasks.map(k => [k.id, k.action, k.name, k.owner, k.start_week, k.weeks, k.depends_on.join(' ')])]));
    if (state.plan.summary) zip.file('plan/project-summary.txt', state.plan.summary +
      (state.plan.sources?.length ? '\n\nSources:\n' + state.plan.sources.map(x => `[${x.id}] ${x.title}${x.cite ? ', ' + x.cite : ''}${x.url ? ' ' + x.url : ''}`).join('\n') : ''));
  }
  if (state.profile) zip.file('utility-profile.json', JSON.stringify(state.profile, null, 2));
  zip.file('README.txt', [
    'ChatWater Resilience export',
    '',
    'proposal.docx                      Draft proposal (Word)',
    'ecam/assessments-ecam-format.json  Load this file in ECAM (climatesmartwater.org/ecam) via "Load and save file"',
    'ecam/results.json                  All ECAM outputs calculated by the app',
    'ecam/results-by-substage.csv       Emissions and energy per substage',
    'actions/selected-actions.json      Options chosen in stage 2, with calculation basis',
    'plan/project-plan.csv              Tasks, owners and timing from stage 3',
    '',
    `Language: ${lang}. Calculations: ECAM v3 by ICRA, IWA and GIZ (CC BY-SA 4.0).`,
  ].join('\n'));
  return zip.generateAsync({ type: 'nodebuffer' });
}

module.exports = { buildProposalDocx, buildZip, expectedText };
