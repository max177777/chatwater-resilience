async function buildZip(state, docxBuffer) {
  const zip = new JSZip();
  const lang = state.lang || 'en';
  const z = ZIP_T[lang] || ZIP_T.en;
  if (docxBuffer) zip.file('proposal.docx', docxBuffer);
  zip.file('ecam/assessments-ecam-format.json', JSON.stringify(state.assessments || [], null, 2));
  const transfer=require('../public/js/project-transfer');
  let backup;
  if(state.projectTransfer) {
    const parsed=transfer.parse(JSON.stringify(state.projectTransfer));
    if(parsed.kind!=='project' || CW.fp(parsed.assessments)!==CW.fp(state.assessments)) throw new Error('Project transfer does not match the exported ECAM data.');
    backup=state.projectTransfer;
  } else {
    try {backup=transfer.pack(state);} catch {backup={format:'chatwater-project',version:1,ecam:state.assessments || [],companion:{format:'unbound',state,note:'Missing identity metadata; restore as unconfirmed with edited text in recovery.'}};}
  }
  zip.file('ecam/application-metadata.json',JSON.stringify(backup.companion,null,2));
  zip.file('project/project-backup.json',JSON.stringify(backup,null,2));
  zip.file('ecam/results.json', JSON.stringify(state.results || [], null, 2));
  if (state.results?.length) {
    const rows = [['assessment', 'stage', 'substage', 'total_kgCO2eq', 'co2', 'ch4_as_co2eq', 'n2o_as_co2eq', 'energy_kWh']];
    for (const r of state.results) for (const s of r.substages)
      rows.push([r.name, `${s.level}/${s.sublevel}`, s.name, s.ghg?.total, s.ghg?.co2, s.ghg?.ch4, s.ghg?.n2o, s.energy_kwh]);
    zip.file('ecam/results-by-substage.csv', csv(rows));
  }
  zip.file('ecam/availability-and-water-balance.json',JSON.stringify((state.results || []).map(r => ({name:r.name,availability:r.availability,validity:r.validity,water_balance:r.water_balance,substages:r.substages.map(s => ({prefix:s.prefix,name:s.name,availability:s.availability,input_availability:s.input_availability}))})),null,2));
  const metas = state.assessmentMeta || [];
  const customEntry = a => {
    const i = metas.findIndex(m => m && m.id === a.assessmentId);
    const ctx = { meta: metas[i], results: (state.results || [])[i] };
    return {
      ...a, origin: 'user', benefit_status: { ...CA.NOT_QUANTIFIED }, scientific_review: 'not_reviewed', emission_classification: null,
      location_text: customLocationText(a, lang, ctx), location_status: CA.resolveLocation(a, ctx.meta).at,
    };
  };
  zip.file('actions/selected-actions.json', JSON.stringify((state.selectedActions || []).map(a => CA.isCustom(a) ? customEntry(a)
    : ({ ...a, benefit_status: benefitStatus(a), addresses: AS.describe(a) })), null, 2));
  if (state.plan?.tasks) {
    zip.file('plan/project-plan.csv', csv([['id', 'action', 'task', 'owner', 'start_week', 'weeks', 'depends_on', 'action_origin'],
      ...state.plan.tasks.map(k => [k.id, k.action, k.name, k.owner, k.start_week, k.weeks, k.depends_on.join(' '), k.action_origin === 'user' ? 'user-proposed' : 'calculated'])]));
    if (state.plan.summary) {
      const head = [`[${state.plan.ai === true ? z.plan_ai : z.plan_template}]`, ...(state.plan.ai === true && CW.mayBeIncomplete(state.plan.summary) ? [`[${z.incomplete}]`] : [])];
      zip.file('plan/project-summary.txt', [...head, '', state.plan.summary].join('\n') +
        (state.plan.sources?.length ? `\n\n${z.sources}\n` + state.plan.sources.map(s => sourceLine(s, lang)).join('\n') : ''));
    }
    // project concept in the team framework's eight areas, with each area's status, checks and review mark
    const cp = state.plan.concept;
    if (cp?.areas?.length) {
      const checkLines = a => {
        const c = a.status === 'ai' ? a.checks || {} : {};
        return [c.unsupported_figures ? uiText('pc_check_figures', lang).replace('{list}', c.unsupported_figures.join(', ')) : null,
          c.unknown_tags ? uiText('pc_check_tags', lang).replace('{list}', c.unknown_tags.join(', ')) : null,
          c.placeholders_dropped ? uiText('pc_check_placeholders', lang) : null,
          a.status === 'ai' && CW.mayBeIncomplete(a.text) ? z.incomplete : null].filter(Boolean).map(x => `> ${z.checks}: ${x}`);
      };
      zip.file('plan/project-concept.md', [`# ${uiText('pc_title', lang)}`, '',
        ...(cp.ai_failed ? [`> ${z.concept_failed}`, ''] : []),
        ...cp.areas.flatMap(a => [`## ${a.n}. ${a.title}`, `_${uiText('pc_status_' + a.status, lang)}${a.reviewed ? ' · ' + z.reviewed : ''}_`, ...checkLines(a), '', String(a.text || ''), '']),
        ...(cp.sources?.length ? [z.sources, ...cp.sources.map(s => sourceLine(s, lang))] : [])].join('\n'));
    }
  }
  if (state.financing?.pathways?.length) {
    zip.file('financing/pathways-to-investigate.json', JSON.stringify({ note: z.pathways_note,
      pathways: require('./pathways').selected(state.financing.pathways, lang).map(({ id, ...x }) => ({ ...x, status: uiText('chat_pathway_status', lang),
        documents: x.documents.map(d => ({ id: d.id, title: d.title, language: d.language, review_status: d.review_status, caveats: d.caveats,
          ...(lang !== 'en' ? { notes_translated: [d.review_status, ...d.caveats].filter(Boolean).map(c => SN.localize(c, lang)) } : {}) })) })) }, null, 2));
  }
  // where generated text drew on the document library: build, searches, retrieved and cited passages
  const provenance = {
    note: z.provenance_note,
    explanations: Object.fromEntries(Object.entries(state.explanationEvidence || {})
      .filter(([key, ev]) => ev && (state.selectedActions || []).some(a => a.key === key))),
    plan_summary: state.plan?.evidence || null,
    proposal_sections: (state.proposal?.sections || []).filter(s => s.evidence).map(s => ({ key: s.key, title: s.title, ai: s.ai, evidence: s.evidence })),
  };
  if (provenance.plan_summary || provenance.proposal_sections.length || Object.keys(provenance.explanations).length) {
    zip.file('evidence/library-provenance.json', JSON.stringify(provenance, null, 2));
  }
  if (state.profile) zip.file('utility-profile.json', JSON.stringify(state.profile, null, 2));
  zip.file('README.txt', z.readme(lang).join('\n'));
  return zip.generateAsync({ type: 'nodebuffer' });
}

