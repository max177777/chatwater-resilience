const note = (text, extra = {}) => new Paragraph({ spacing: { before: 60, after: 160, line: 260 }, keepLines: true, ...extra,
  children: [new TextRun({ text: MD.chem(text), size: MD.SIZE.note, color: MD.COLORS.muted })] });
